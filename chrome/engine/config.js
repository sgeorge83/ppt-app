const LEGACY_THEMES = { midnight: "air", sanctuary: "parchment", light: "linen", classic: "chapel" };

export function getTheme(themeId) {
  const resolved = THEMES.some((theme) => theme.id === themeId) ? themeId : LEGACY_THEMES[themeId] || "air";
  return THEMES.find((theme) => theme.id === resolved) || THEMES[0];
}
